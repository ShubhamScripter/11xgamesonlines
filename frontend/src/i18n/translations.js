export const USER_LANGUAGES = ['en', 'bn', 'hn'];

export const LANGUAGE_LABELS = {
  en: 'EN',
  bn: 'BN',
  hn: 'HN',
};

export const LANGUAGE_FULL_NAMES = {
  en: 'English',
  bn: 'বাংলা',
  hn: 'हिन्दी',
};

export const LANGUAGE_STORAGE_KEY = 'baaji_preferred_language';

export function normalizeLanguage(value) {
  const lang = String(value || '').trim().toLowerCase();
  return USER_LANGUAGES.includes(lang) ? lang : 'en';
}

export function getStoredLanguage() {
  try {
    return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY));
  } catch {
    return 'en';
  }
}

export function setStoredLanguage(lang) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, normalizeLanguage(lang));
  } catch {
    // ignore
  }
}

